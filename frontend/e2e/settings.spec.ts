import { test, expect, type Page } from '@playwright/test'

async function cleanPresets(page: Page) {
  const response = await page.request.get('/api/llm/presets')
  for (const preset of await response.json()) await page.request.delete('/api/llm/presets/' + preset.id)
}

async function addPreset(page: Page, name: string) {
  await page.getByRole('button', { name: 'เพิ่ม preset', exact: true }).first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('ชื่อ preset', { exact: true }).fill(name)
  await dialog.getByLabel('Model ID', { exact: true }).fill('model-test')
  await dialog.getByLabel('Base URL', { exact: true }).fill('https://provider.example/v1')
  await dialog.getByLabel('API key', { exact: true }).fill('browser-test-secret')
  await dialog.getByRole('button', { name: 'บันทึก preset', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('radio', { name: `ตั้ง ${name} เป็น default` })).toBeVisible()
}

test('thresholds persist; controls sync; invalid edits and unsaved navigation are handled', async ({ page }) => {
  const errors: string[]=[]
  page.on('pageerror', error => errors.push(error.message))
  await page.request.patch('/api/text-quality/thresholds', { data: { max_thai_percent: 50, max_garbled_thai_percent: 5, min_text_chars: 50, max_image_percent: 80 } })
  await page.goto('/')
  const input = page.getByRole('spinbutton', { name: 'สัดส่วนภาษาไทย', exact: true })
  await expect(input).toHaveValue('50')
  const save = page.getByRole('button', { name: 'บันทึก', exact: true })
  await expect(save).toBeDisabled()
  await input.fill('65')
  await expect(page.getByRole('slider', { name: 'สัดส่วนภาษาไทย', exact: true })).toHaveAttribute('aria-valuenow', '65')
  await page.getByRole('tab', { name: 'LLM Model' }).click()
  await expect(page.getByRole('alertdialog')).toBeVisible()
  await page.getByRole('button', { name: 'อยู่ต่อ', exact: true }).click()
  await expect(input).toHaveValue('65')
  await save.click()
  await expect(page.getByText('บันทึกการตั้งค่าแล้ว', { exact: true })).toBeVisible()
  await page.reload()
  await expect(input).toHaveValue('65')
  await input.fill('101')
  await expect(input).toHaveAttribute('aria-invalid','true')
  await expect(save).toBeDisabled()
  await page.getByRole('button', { name: 'ยกเลิก', exact: true }).click()
  await expect(input).toHaveValue('65')
  await input.fill('64')
  await page.getByRole('tab', { name: 'LLM Model' }).click()
  await page.getByRole('button', { name: 'ทิ้งการแก้ไข', exact: true }).click()
  await expect(page.getByText('Model presets', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'เกณฑ์คุณภาพข้อความ', exact: true }).click()
  await expect(input).toHaveValue('65')
  await page.screenshot({ path:'test-results/settings-desktop.png', fullPage:true })
  await page.setViewportSize({ width:390,height:844 })
  await expect(input).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path:'test-results/settings-mobile.png',fullPage:true })
  expect(errors).toEqual([])
})

test('presets create, edit without revealing key, switch default and delete with fallback', async ({ page }) => {
  await cleanPresets(page)
  await page.goto('/')
  await page.getByRole('tab', { name:'LLM Model' }).click()
  await expect(page.getByRole('heading', { name:'ยังไม่มี preset' })).toBeVisible()
  await addPreset(page,'First')
  await expect(page.getByRole('radio', { name:'ตั้ง First เป็น default' })).toBeChecked()
  await addPreset(page,'Second')
  await page.getByRole('radio', { name:'ตั้ง Second เป็น default' }).click()
  await expect(page.getByRole('radio', { name:'ตั้ง Second เป็น default' })).toBeChecked()
  await page.getByRole('button', { name:'เมนู First',exact:true }).click()
  await page.getByRole('menuitem', { name:'แก้ไข',exact:true }).click()
  const dialog=page.getByRole('dialog')
  await expect(dialog.getByLabel('API key', { exact:true })).toHaveValue('')
  await dialog.getByLabel('Model ID', { exact:true }).fill('changed-model')
  await dialog.getByRole('button', { name:'บันทึกการแก้ไข',exact:true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByText('changed-model', { exact:true })).toBeVisible()
  await page.getByRole('button', { name:'เมนู Second',exact:true }).click()
  await page.getByRole('menuitem', { name:'ลบ',exact:true }).click()
  await expect(page.getByRole('alertdialog')).toContainText('preset นี้เป็น default')
  await page.getByRole('button', { name:'ลบ preset',exact:true }).click()
  await expect(page.getByRole('alertdialog')).not.toBeVisible()
  await expect(page.getByRole('radio', { name:'ตั้ง First เป็น default' })).toBeChecked()
  await page.reload()
  await page.getByRole('tab', { name:'LLM Model' }).click()
  await expect(page.getByText('changed-model', { exact:true })).toBeVisible()
  await expect(page.getByText('browser-test-secret', { exact:true })).toHaveCount(0)
  await page.screenshot({ path:'test-results/settings-presets.png',fullPage:true })
})

test('load and save failures preserve edits and support retry', async ({ page }) => {
  let failing=true
  await page.route('**/api/text-quality/thresholds', async route => {
    if (failing) await route.fulfill({ status:500,json:{code:'internal_error',error_code:'SYS_002'} })
    else await route.continue()
  })
  await page.goto('/')
  await expect(page.getByText('โหลดเกณฑ์ไม่สำเร็จ', { exact:true })).toBeVisible()
  await expect(page.getByRole('spinbutton')).toHaveCount(0)
  failing=false
  await page.getByRole('button', { name:'ลองอีกครั้ง',exact:true }).click()
  const input=page.getByRole('spinbutton', { name:'สัดส่วนภาษาไทย',exact:true })
  await expect(input).toBeVisible()
  await input.fill('77')
  failing=true
  await page.getByRole('button', { name:'บันทึก',exact:true }).click()
  await expect(page.getByText('บันทึกไม่สำเร็จ', { exact:true })).toBeVisible()
  await expect(input).toHaveValue('77')
  failing=false
  await page.getByRole('button', { name:'ลองอีกครั้ง',exact:true }).click()
  await expect(page.getByText('บันทึกการตั้งค่าแล้ว', { exact:true })).toBeVisible()
})

test('connection errors identify fields, clear on edit and do not prevent saving', async ({ page }) => {
  await cleanPresets(page)
  await page.route('**/api/llm/presets/test', async route => {
    expect(route.request().postDataJSON()).toEqual({ model_id:'test-model',base_url:'https://provider.example/v1',api_key:'fake-key' })
    await route.fulfill({ json:{ok:false,field:'api_key',reason:'unauthorized',upstream_status:401} })
  })
  await page.goto('/')
  await page.getByRole('tab', { name:'LLM Model' }).click()
  await page.getByRole('button', { name:'เพิ่ม preset',exact:true }).first().click()
  const dialog=page.getByRole('dialog')
  await dialog.getByLabel('Model ID', { exact:true }).fill('test-model')
  await dialog.getByLabel('Base URL', { exact:true }).fill('https://provider.example/v1')
  await dialog.getByLabel('API key', { exact:true }).fill('fake-key')
  await dialog.getByRole('button', { name:'ทดสอบการเชื่อมต่อ',exact:true }).click()
  await expect(dialog.getByLabel('API key', { exact:true })).toHaveAttribute('aria-invalid','true')
  await expect(dialog.getByText('เชื่อมต่อไม่สำเร็จ', { exact:true })).toBeVisible()
  await dialog.getByLabel('ชื่อ preset', { exact:true }).fill('Connection failure allowed')
  await expect(dialog.getByText('เชื่อมต่อไม่สำเร็จ', { exact:true })).not.toBeVisible()
  await dialog.getByRole('button', { name:'ทดสอบการเชื่อมต่อ',exact:true }).click()
  await expect(dialog.getByText('เชื่อมต่อไม่สำเร็จ', { exact:true })).toBeVisible()
  await dialog.getByRole('button', { name:'บันทึก preset',exact:true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('radio', { name:'ตั้ง Connection failure allowed เป็น default' })).toBeChecked()
})

test('duplicate names and deletion failures retain their dialogs for retry', async ({ page }) => {
  await cleanPresets(page)
  await page.goto('/')
  await page.getByRole('tab', { name:'LLM Model' }).click()
  await addPreset(page,'Original')
  await page.getByRole('button', { name:'เพิ่ม preset',exact:true }).first().click()
  const dialog=page.getByRole('dialog')
  await dialog.getByLabel('ชื่อ preset', { exact:true }).fill('original')
  await dialog.getByLabel('Model ID', { exact:true }).fill('m')
  await dialog.getByLabel('Base URL', { exact:true }).fill('https://provider.example/v1')
  await dialog.getByLabel('API key', { exact:true }).fill('fake-key')
  await dialog.getByRole('button', { name:'บันทึก preset',exact:true }).click()
  await expect(dialog.getByText('มี preset ชื่อนี้อยู่แล้ว', { exact:true })).toBeVisible()
  await expect(dialog.getByLabel('ชื่อ preset', { exact:true })).toBeFocused()
  await dialog.getByRole('button', { name:'ยกเลิก',exact:true }).click()
  let fail=true
  await page.route('**/api/llm/presets/*',async route => {
    if (fail && route.request().method()==='DELETE') await route.fulfill({status:500,json:{error_code:'SYS_002'}})
    else await route.continue()
  })
  await page.getByRole('button', { name:'เมนู Original',exact:true }).click()
  await page.getByRole('menuitem', { name:'ลบ',exact:true }).click()
  await page.getByRole('button', { name:'ลบ preset',exact:true }).click()
  await expect(page.getByRole('alertdialog').getByRole('alert')).toContainText('ลบไม่สำเร็จ')
  fail=false
  await page.getByRole('button', { name:'ลบ preset',exact:true }).click()
  await expect(page.getByRole('alertdialog')).not.toBeVisible()
  await expect(page.getByRole('heading', { name:'ยังไม่มี preset' })).toBeVisible()
})
